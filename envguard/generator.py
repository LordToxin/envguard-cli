"""Automated generator for sanitized .env.example templates."""

from typing import Any, List, Optional, Union
import os
import re
from envguard.parser import parse_dotenv, EnvEntry

PLACEHOLDER_MAP = {
    r"PORT": "3000",
    r"HOST": "localhost",
    r"NODE_ENV": "development",
    r"ENVIRONMENT": "development",
    r"DEBUG": "true",
    r"(?:DATABASE|DB)_URL": "postgres://user:password@localhost:5432/mydb",
    r"REDIS_URL": "redis://localhost:6379",
    r"OPENAI_API_KEY": "sk-your-openai-api-key-here",
    r"ANTHROPIC_API_KEY": "sk-ant-your-claude-api-key-here",
    r"STRIPE_SECRET_KEY": "sk_test_your_stripe_secret_key",
    r"STRIPE_PUBLISHABLE_KEY": "pk_test_your_stripe_publishable_key",
    r"GITHUB_TOKEN": "ghp_your_github_personal_token",
    r"SLACK_WEBHOOK_URL": "https://hooks.slack.com/services/YOUR/WEBHOOK/URL",
    r"JWT_SECRET": "your-super-secret-jwt-key-min-32-chars",
    r"SESSION_SECRET": "your-secure-random-session-secret",
    r"AWS_ACCESS_KEY_ID": "AKIAIOSFODNN7EXAMPLE",
    r"AWS_SECRET_ACCESS_KEY": "wJalrXUtnFEMI/K7MDENG/bPxRfiCYEXAMPLEKEY",
    r"AWS_REGION": "us-east-1",
    r"EMAIL": "support@example.com",
}

def guess_placeholder(key: str, existing_val: str) -> str:
    """Guess an appropriate sanitization placeholder for a variable key."""
    for pattern, placeholder in PLACEHOLDER_MAP.items():
        if re.search(f"^{pattern}$", key, re.IGNORECASE):
            return placeholder

    # Heuristic guess based on keywords
    key_upper = key.upper()
    if "PORT" in key_upper:
        return "8080"
    if "URL" in key_upper or "URI" in key_upper:
        return "https://example.com/api"
    if "PASSWORD" in key_upper or "SECRET" in key_upper or "KEY" in key_upper or "TOKEN" in key_upper:
        return "your_" + key.lower() + "_here"
    if "ENABLE" in key_upper or "DISABLE" in key_upper or "IS_" in key_upper:
        return "true"

    # Default fallback
    if len(existing_val) < 15 and not any(c in existing_val for c in "/:?#@"):
        return existing_val
    return "your_" + key.lower() + "_here"

def generate_template(entries: Any, include_comments: bool = True) -> str:
    """Synthesize clean .env.example content from parsed EnvEntries or raw string."""
    if isinstance(entries, str):
        entries = parse_dotenv(entries)

    output_lines = [
        "# Auto-generated by EnvGuard CLI",
        "# Copy this file to .env and configure local values",
        "",
    ]

    for entry in entries:
        if include_comments and entry.comment:
            output_lines.append(f"# {entry.comment}")

        placeholder = guess_placeholder(entry.key, entry.value)
        prefix = "export " if entry.is_exported else ""

        # Quote if has spaces
        if " " in placeholder:
            placeholder = f'"{placeholder}"'

        output_lines.append(f"{prefix}{entry.key}={placeholder}")

    output_lines.append("")
    return "\n".join(output_lines)

def extract_env_vars_from_code(directory: str) -> List[str]:
    """Scan source code for environment variable usages (Python, JS/TS, Go, Rust)."""
    env_keys = set()
    patterns = [
        re.compile(r"process\.env\.([A-Z0-9_]+)"),
        re.compile(r"os\.environ\[['\"]([A-Z0-9_]+)['\"]\]"),
        re.compile(r"os\.getenv\(['\"]([A-Z0-9_]+)['\"]\)"),
        re.compile(r"os\.LookupEnv\(['\"]([A-Z0-9_]+)['\"]\)"),
        re.compile(r"std::env::var\(['\"]([A-Z0-9_]+)['\"]\)"),
    ]

    valid_extensions = {".py", ".js", ".ts", ".jsx", ".tsx", ".go", ".rs", ".yaml", ".yml"}

    for root, dirs, files in os.walk(directory):
        # Ignore common non-source directories
        dirs[:] = [d for d in dirs if d not in {".git", "node_modules", "dist", "build", ".venv", "__pycache__"}]
        for f in files:
            ext = os.path.splitext(f)[1]
            if ext in valid_extensions:
                filepath = os.path.join(root, f)
                try:
                    with open(filepath, "r", encoding="utf-8", errors="ignore") as handle:
                        text = handle.read()
                        for p in patterns:
                            matches = p.findall(text)
                            for m in matches:
                                env_keys.add(m)
                except Exception:
                    pass

    return sorted(list(env_keys))
